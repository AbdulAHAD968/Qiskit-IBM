"""Write DOCS/BENCHMARKS.md from the saved results.

    python -m kinship.report_md
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
TARGET = ROOT / "DOCS" / "BENCHMARKS.md"

NAMES = {"random": "Random valid plan", "field": "Field officer's rule", "relevance": "Relevance-weighted rule",
         "greedy": "Greedy", "annealing": "Simulated annealing", "constrained": "Constrained QAOA",
         "penalty": "Penalty QAOA", "decomposed_qaoa": "Decomposition + QAOA",
         "decomposed_exact": "Decomposition + exact components"}


def load(name):
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def pct(v, digits=0):
    return f"{100 * v:.{digits}f}%"


def small(v):
    return f"{100 * v:.{3 if v < 0.001 else 2 if v < 0.01 else 1}f}%"


def table(header, rows, align=None):
    align = align or ["l"] * len(header)
    out = ["| " + " | ".join(header) + " |",
           "|" + "|".join("---:" if a == "r" else "---" for a in align) + "|"]
    out += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return "\n".join(out)


def build() -> str:
    meta, gen, g1, bench = load("meta"), load("genetics"), load("gate1"), load("benchmark")
    circ, noise, abl, tr, dec, demo = (load("circuits"), load("noise"), load("ablation"), load("tradeoff"),
                                       load("decomposition"), load("demo"))
    cfg = bench["config"]
    parts = ["# Benchmark report", "",
             "Every number below is read from `results/*.json`. This file is generated by "
             "`python -m kinship.report_md`; do not edit it by hand.", "",
             "## Environment", "",
             table(["Item", "Value"], [
                 ["Generated (UTC)", meta["generated"]],
                 ["Python", meta["python"]], ["Qiskit", meta["qiskit"]], ["Qiskit Aer", meta["qiskit_aer"]],
                 ["NumPy / SciPy", f"{meta['numpy']} / {meta['scipy']}"],
                 ["Hardware", meta["hardware"]],
                 ["Optimiser", f"COBYLA, at most {cfg['maxiter']} iterations per start"],
                 ["Shots per read-out", f"{cfg['shots']:,}"],
                 ["Instances", f"{cfg['n_s']} of size S (10 relatives, 4 kits), {cfg['n_m']} of size M (16 relatives, 5 kits)"],
                 ["Total run time", f"{sum(meta['seconds'].values()) / 60:.1f} minutes on {meta['workers']} processes"],
             ]), "",
             "Definitions. *Quality*: expected value of a measured valid plan, scaled so that the worst valid plan is 0 "
             "and the best is 1; shots that break the kit limit are discarded first. *Best plan per shot*: probability "
             "that a single shot is an optimal plan, counted over all shots. *Valid shots*: "
             "share of shots that use exactly k kits. *Shots for 95%*: shots needed to see an optimal plan with 95 "
             "percent probability (median over instances).", ""]

    parts += ["## 1. Pedigree engine against textbook values", "",
              table(["Relative of the affected child", "Textbook", "Exact formula", "Engine"],
                    [[c["relation"], c["textbook"], c.get("formula", ""), f"{c['computed']:.4f}"] for c in gen["checks"]],
                    ["l", "l", "l", "r"]), ""]
    cal = gen["calibration"]
    parts += [f"Calibration over {cal['families']} synthetic families: carrier share among testable relatives "
              f"{pct(cal['carrier_share_candidates'], 1)} (31% of tested relatives in Ahmed et al. 2002); both partners "
              f"carriers among married couples other than the index parents "
              f"{pct(cal['couples_both_carriers_excluding_index_parents'], 1)}, and "
              f"{pct(cal['couples_both_carriers_all_married'], 1)} when the index parents are counted (8% of all married "
              "couples in the much larger families of that study).", ""]

    mc_path = RESULTS / "genetics_montecarlo.json"
    if mc_path.exists():
        mc = json.loads(mc_path.read_text(encoding="utf-8"))
        parts += [f"Independent check (`python -m kinship.validate_genetics`): a Monte Carlo gene-dropping simulation "
                  f"with rejection sampling, which shares no code with the engine's inference, was compared with the "
                  f"exact values on {len(mc['cases'])} families.", "",
                  table(["Family", "People", "Accepted samples", "Simulated families", "Probabilities compared",
                         "Largest deviation (standard errors)"],
                        [[c["instance"], c["people"], f"{c['accepted']:,}", f"{c['simulated']:,}", c["comparisons"],
                          f"{c['max_abs_z']:.2f}"] for c in mc["cases"]], ["l", "r", "r", "r", "r", "r"]), "",
                  f"Over all {mc['comparisons']} carrier and couple probabilities the largest deviation is "
                  f"{mc['max_abs_z']:.2f} standard errors; {pct(mc['share_above_2'], 1)} lie beyond two standard errors "
                  "(about 5% expected by chance).", ""]
    parts += ["## 2. Is the problem trivial? Classical rules against the exact optimum", "",
              f"{g1['n_instances']} seeded families per size.", ""]
    rows = []
    for size in ("S", "M"):
        for key in ("random", "field", "relevance", "greedy", "annealing"):
            s = g1["summary"][size][key]
            rows.append([size, NAMES[key], pct(s["ratio"]["mean"], 1), pct(s["ratio"]["min"], 1),
                         pct(s["miss_rate"]) if "miss_rate" in s else ""])
    parts += [table(["Size", "Rule", "Value / optimum, mean", "Worst family", "Misses the best plan"], rows,
                    ["l", "l", "r", "r", "r"]), ""]
    for size in ("S", "M"):
        s = g1["summary"][size]
        parts.append(f"Size {size}: {s['edges']['mean']:.1f} couple links on average; the couple term carries "
                     f"{pct(s['couple_share_of_optimum']['mean'])} of the best plan's value; the largest connected "
                     f"component of the couple graph has {s['largest_component']['mean']:.1f} people on average "
                     f"(maximum {s['largest_component']['max']:.0f}).")
    parts.append("")
    for size in ("S", "M"):
        t = g1["summary"][size]["field"]["tie_break"]
        parts.append(f"Tie-breaking, size {size}: the field officer's rule has a tie in carrier probability at the "
                     f"cut-off in {t['families_with_tie']} of {g1['n_instances']} families. Breaking every tie in its "
                     f"favour gives {pct(t['best_ratio']['mean'], 1)} of the optimum on average (every tie against it: "
                     f"{pct(t['worst_ratio']['mean'], 1)}), and it still misses the best plan in "
                     f"{pct(t['best_miss_rate'])} of the families.")
    parts += ["", "![Field rule gap](../results/figures/fig02_field_rule_gap.png)", ""]

    parts += ["## 3. QAOA against the references", ""]
    rows = []
    for r in sorted(bench["summary"], key=lambda r: ("SM".index(r["size"]), r["kind"] == "quantum",
                                                     list(NAMES).index(r["method"]), r["p"] or 0)):
        q = r["quality"]
        rows.append([
            r["size"], NAMES[r["method"]], r["p"] or "",
            f"{q['mean']:.3f} +/- {q['std']:.3f}", pct(r["ratio"]["mean"], 1),
            small(r["p_opt"]["mean"]) if "p_opt" in r else "",
            f"{r['p_opt_gain']['mean']:.1f}x" if "p_opt_gain" in r else "",
            pct(r["valid_share"]["mean"]) if "valid_share" in r else "100%",
            f"{r['shots_95']['median']:,.0f}" if r.get("shots_95", {}).get("median") is not None else "",
            pct(r["best_sample_optimal_share"]) if "best_sample_optimal_share" in r
            else pct(r["optimal_share"]) if "optimal_share" in r else "",
        ])
    parts += [table(["Size", "Method", "p", "Quality", "Value / optimum", "Best plan per shot", "Gain over random",
                     "Valid shots", "Shots for 95%", "Returns the best plan"], rows,
                    ["l", "l", "r", "r", "r", "r", "r", "r", "r", "r"]), "",
              "\"Returns the best plan\": for the classical rules, the share of instances where the rule's plan is "
              "optimal; for QAOA, the share where the best of the measured plans is optimal. With thousands of shots and "
              "only 210 or 4,368 valid plans the latter is a weak statement, so read the per-shot columns.", "",
              "![Quality against depth](../results/figures/fig03_quality_vs_depth.png)", "",
              "![Probability of the best plan](../results/figures/fig04_probability_of_best_plan.png)", "",
              "![Valid shots](../results/figures/fig05_valid_shots.png)", ""]

    parts += ["## 4. Circuit cost", "",
              "Transpiled to the basis RZ, SX, X, CZ at optimisation level 3, first instance of each size.", ""]
    rows = []
    for size in [s for s in ("S", "M") if any(r["size"] == s for r in circ["rows"])]:
        for method in ("dicke_only", "constrained", "penalty"):
            for p in sorted({r["p"] for r in circ["rows"] if r["method"] == method}):
                a = next(r for r in circ["rows"] if r["size"] == size and r["method"] == method and r["p"] == p
                         and r["topology"] == "all-to-all")
                b = next(r for r in circ["rows"] if r["size"] == size and r["method"] == method and r["p"] == p
                         and r["topology"] == "line")
                label = "Dicke start state alone" if method == "dicke_only" else NAMES[method]
                rows.append([f"{size} ({a['n']} qubits)", label, p or "", a["two_qubit"], a["depth"], b["two_qubit"],
                             b["depth"]])
    parts += [table(["Size", "Circuit", "p", "CZ gates, all-to-all", "Depth, all-to-all", "CZ gates, line", "Depth, line"],
                    rows, ["l", "l", "r", "r", "r", "r", "r"]), "",
              "![Circuit cost](../results/figures/fig08_circuit_cost.png)", ""]

    parts += ["## 5. Noise sweep", "", f"Model: {noise['model']}. Size S, {noise['instances']} families, "
              f"{noise['shots']:,} shots. Shots without exactly k ones are discarded. The two-qubit error is the "
              "depolarising probability applied after each CZ gate. Simulator only.", ""]
    rows = [[NAMES[r["method"]], r["p"], "0" if r["e2"] == 0 else f"{100 * r['e2']:g}%", f"{r['two_qubit']['mean']:.0f}",
             pct(r["valid_share"]["mean"], 1), f"{r['quality']['mean']:.3f}", small(r["p_opt"]["mean"])]
            for r in noise["summary"]]
    ref = noise["summary"][0]
    parts += [table(["Method", "p", "Two-qubit error", "CZ gates", "Valid shots", "Quality of valid shots",
                     "Best plan per shot"], rows, ["l", "r", "r", "r", "r", "r", "r"]), "",
              f"Reference: a random valid plan has quality {ref['random_quality']['mean']:.3f} and a "
              f"{small(ref['random_p_opt']['mean'])} chance of being the best plan.", "",
              "![Noise](../results/figures/fig06_noise.png)", ""]

    parts += ["## 6. Start-state ablation (did not work)", "",
              f"Constrained QAOA started from the field officer's plan (k X gates) instead of the Dicke state, "
              f"{abl['instances']} size-S instances.", ""]
    rows = [["Dicke state" if r["initial"] == "dicke" else "Field officer's plan", r["p"], f"{r['quality']['mean']:.3f}",
             small(r["p_opt"]["mean"])] for r in abl["summary"]]
    parts += [table(["Start state", "p", "Quality", "Best plan per shot"], rows, ["l", "r", "r", "r"]), ""]

    hv = tr["hypervolume"]
    parts += ["## 7. Trade-off curve", "",
              f"Instance {tr['instance']} ({tr['selection']}), depth {tr['p']}, {tr['shots_per_lambda']} shots for each of "
              f"{len(tr['lambdas'])} values of lambda ({tr['total_shots']:,} shots in total, {tr['distinct_plans_sampled']:,} "
              f"distinct plans out of {tr['n_feasible']:,}).", "",
              table(["Measure", "QAOA shots", "Uniform random sampling, same number of shots"], [
                  [f"Plans of the exact front found (of {tr['front_points']['exact']})", tr["front_points"]["qaoa_found"],
                   f"{tr['front_points']['random_found_mean']:.2f} on average"],
                  ["Share of the area under the exact front", pct(hv["qaoa_ratio"], 1),
                   f"{pct(hv['random_ratio_mean'], 1)} +/- {pct(hv['random_ratio_std'], 1)}"],
              ]), "", "One instance only: an illustration, not a general claim.", "",
              "![Trade-off](../results/figures/fig07_tradeoff.png)", ""]

    parts += ["## 8. Linked families: decomposition along the couple graph", ""]
    rows = []
    for r in dec["rows"]:
        rows.append([r["instance"], r["n"], r["k"], r["edges"], r["max_qubits"], r["qaoa_runs"],
                     pct(r["decomposed_qaoa"]["ratio"], 1), pct(r["field"]["ratio"], 1), pct(r["relevance"]["ratio"], 1),
                     pct(r["greedy"]["ratio"], 1), pct(r["annealing"]["ratio"], 1),
                     "yes" if r["exact"]["proven_optimal"] else "no"])
    parts += [table(["Network", "Relatives", "Kits", "Couple links", "Largest circuit (qubits)", "QAOA runs",
                     "Decomposition + QAOA", "Field rule", "Relevance rule", "Greedy", "Annealing",
                     "Optimum proven by the integer programme"], rows,
                    ["l", "r", "r", "r", "r", "r", "r", "r", "r", "r", "r", "l"]), "",
              "Values are divided by the optimum of the integer programme. QAOA is run on every connected component "
              "with at least three people and every budget that leaves a real choice; pairs and isolated people are "
              "handled in closed form. At these component sizes sampling finds each component optimum easily.", "",
              "![Decomposition](../results/figures/fig09_decomposition.png)", ""]

    q3 = [q for q in demo["qaoa"] if q["method"] == "constrained"][-1]
    fld = demo["plans"]["field"]
    parts += ["## 9. Worked example", "",
              f"Instance {demo['name']} ({demo['selection']}).", "",
              table(["Plan", "Relatives tested", "At-risk couples found (expected)", "Value / optimum"], [
                  ["Field officer's rule", ", ".join(fld["labels"]), f"{fld['couples']:.3f}", pct(fld["ratio"])],
                  ["Relevance-weighted rule", ", ".join(demo["plans"]["relevance"]["labels"]),
                   f"{demo['plans']['relevance']['couples']:.3f}", pct(demo["plans"]["relevance"]["ratio"])],
                  ["Greedy", ", ".join(demo["plans"]["greedy"]["labels"]), f"{demo['plans']['greedy']['couples']:.3f}",
                   pct(demo["plans"]["greedy"]["ratio"])],
                  [f"Constrained QAOA, depth {q3['p']}, best measured plan", ", ".join(q3["best"]["labels"]),
                   f"{q3['best']['couples']:.3f}", pct(q3["best"]["ratio"])],
                  ["Exact optimum", ", ".join(demo["plans"]["exact"]["labels"]),
                   f"{demo['plans']['exact']['couples']:.3f}", "100%"],
              ], ["l", "l", "r", "r"]), "",
              f"Chance that one QAOA shot is the best plan: {pct(q3['p_opt'], 1)}; random valid plan: "
              f"{pct(demo['random']['p_opt'], 2)}.", "",
              "![Worked example](../results/figures/fig01_pedigree_plans.png)", "",
              "## Reproduce", "", "```bash", "pip install -r requirements.txt",
              "python -m kinship.evaluate all      # results/*.json", "python -m kinship.plots             # results/figures/*.png",
              "python -m kinship.report_md         # this file", "python -m kinship.export_web        # website data",
              "python report/build_report.py       # the .docx report", "```", ""]
    return "\n".join(parts)


def main() -> int:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(build(), encoding="utf-8")
    print("wrote", TARGET.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
